CREATE DATABASE IF NOT EXISTS agent_flow DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE agent_flow;

CREATE TABLE IF NOT EXISTS `app_user` (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  username VARCHAR(64) NOT NULL,
  password VARCHAR(128) NOT NULL,
  nickname VARCHAR(64) DEFAULT NULL,
  role VARCHAR(32) NOT NULL DEFAULT 'ADMIN',
  avatar VARCHAR(255) DEFAULT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_user_username (username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS workflow (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(128) NOT NULL,
  description VARCHAR(512) DEFAULT NULL,
  engine_type VARCHAR(32) NOT NULL DEFAULT 'langgraph',
  flow_data LONGTEXT NOT NULL,
  status TINYINT NOT NULL DEFAULT 1 COMMENT '1=草稿 2=已发布',
  version INT NOT NULL DEFAULT 1,
  user_id BIGINT DEFAULT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_workflow_user (user_id),
  KEY idx_workflow_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS node_definition (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  type VARCHAR(64) NOT NULL,
  name VARCHAR(64) NOT NULL,
  category VARCHAR(32) NOT NULL,
  icon VARCHAR(64) DEFAULT NULL,
  color VARCHAR(32) DEFAULT NULL,
  description VARCHAR(255) DEFAULT NULL,
  config_schema LONGTEXT,
  sort INT NOT NULL DEFAULT 0,
  enabled TINYINT NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_node_type (type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS execution_record (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  run_id VARCHAR(64) NOT NULL,
  workflow_id BIGINT NOT NULL,
  workflow_name VARCHAR(128) DEFAULT NULL,
  user_id BIGINT DEFAULT NULL,
  status VARCHAR(16) NOT NULL COMMENT 'RUNNING/SUCCESS/FAILED/CANCELED',
  input_data LONGTEXT,
  output_data LONGTEXT,
  error_message TEXT,
  node_count INT NOT NULL DEFAULT 0,
  elapsed_ms BIGINT DEFAULT 0,
  started_at DATETIME DEFAULT NULL,
  finished_at DATETIME DEFAULT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uk_execution_run_id (run_id),
  KEY idx_execution_workflow (workflow_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS execution_node_log (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  run_id VARCHAR(64) NOT NULL,
  workflow_id BIGINT NOT NULL,
  node_id VARCHAR(64) NOT NULL,
  node_type VARCHAR(64) DEFAULT NULL,
  node_name VARCHAR(128) DEFAULT NULL,
  seq INT NOT NULL DEFAULT 0,
  status VARCHAR(16) NOT NULL,
  input_data LONGTEXT,
  output_data LONGTEXT,
  error_message TEXT,
  elapsed_ms BIGINT DEFAULT 0,
  started_at DATETIME DEFAULT NULL,
  finished_at DATETIME DEFAULT NULL,
  KEY idx_node_log_run (run_id, seq)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS llm_provider_config (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  provider VARCHAR(32) NOT NULL COMMENT '同 ai-service providers 注册表的 key',
  base_url VARCHAR(255) DEFAULT NULL COMMENT '自定义 OpenAI 兼容地址',
  api_key VARCHAR(512) DEFAULT NULL COMMENT '前端保存的 Key，仅 Java 侧读取',
  enabled TINYINT NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_llm_provider (provider)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='服务商凭据配置';

CREATE TABLE IF NOT EXISTS knowledge_base (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(128) NOT NULL,
  description VARCHAR(512) DEFAULT NULL,
  embedding_provider VARCHAR(32) NOT NULL DEFAULT 'mock',
  embedding_model VARCHAR(64) NOT NULL DEFAULT 'text-embedding-3-small',
  chunk_size INT NOT NULL DEFAULT 600,
  chunk_overlap INT NOT NULL DEFAULT 80,
  user_id BIGINT DEFAULT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='知识库';

CREATE TABLE IF NOT EXISTS knowledge_document (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  knowledge_base_id BIGINT NOT NULL,
  title VARCHAR(255) NOT NULL,
  source_type VARCHAR(16) NOT NULL DEFAULT 'TEXT',
  content LONGTEXT NOT NULL,
  char_count INT NOT NULL DEFAULT 0,
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  chunk_count INT NOT NULL DEFAULT 0,
  error_message VARCHAR(1024) DEFAULT NULL,
  deleted TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_knowledge_doc_base (knowledge_base_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='知识库文档';

CREATE TABLE IF NOT EXISTS knowledge_chunk (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  knowledge_base_id BIGINT NOT NULL,
  document_id BIGINT NOT NULL,
  chunk_index INT NOT NULL DEFAULT 0,
  content LONGTEXT NOT NULL,
  char_count INT NOT NULL DEFAULT 0,
  embedding LONGTEXT,
  embedding_model VARCHAR(64) DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_knowledge_chunk_base (knowledge_base_id),
  KEY idx_knowledge_chunk_doc (document_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='知识库分片';
